using Npgsql;
// TODO: Add 3DS stuff
public static class DatabaseInitializer
{
    private const string Schema = @"
        CREATE TABLE IF NOT EXISTS mnids (
            pid              INTEGER PRIMARY KEY,
            username         TEXT    NOT NULL,
            username_lower   TEXT    NOT NULL UNIQUE,
            password         TEXT    NOT NULL,
            birthdate        TEXT    NOT NULL,
            gender           TEXT    NOT NULL,
            country          TEXT    NOT NULL,
            language         TEXT    NOT NULL,
            region           INTEGER NOT NULL,
            timezone_name    TEXT    NOT NULL,
            timezone_offset  BIGINT  NOT NULL,

            email_address    TEXT    NOT NULL,
            email_id         BIGINT  NOT NULL,
            email_primary    BOOLEAN NOT NULL DEFAULT FALSE,
            email_parent     BOOLEAN NOT NULL DEFAULT FALSE,
            email_validated  BOOLEAN NOT NULL DEFAULT FALSE,
            email_code       TEXT    NOT NULL,
            email_token      TEXT    NOT NULL,

            mii_name         TEXT    NOT NULL,
            mii_primary      BOOLEAN NOT NULL DEFAULT FALSE,
            mii_data         TEXT    NOT NULL,
            mii_id           BIGINT  NOT NULL,
            mii_hash         TEXT    NOT NULL,
            mii_image_id     BIGINT  NOT NULL,

            flag_marketing   BOOLEAN NOT NULL DEFAULT FALSE,
            flag_off_device  BOOLEAN NOT NULL DEFAULT FALSE,

            created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            email_validated_at TIMESTAMPTZ,
            flag_active      BOOLEAN NOT NULL DEFAULT TRUE,
            email_reachable  BOOLEAN NOT NULL DEFAULT FALSE,
            access_level      INTEGER NOT NULL DEFAULT 0
        );


        CREATE TABLE IF NOT EXISTS oauthtokens (
            token          TEXT PRIMARY KEY, 
            refresh_token  TEXT NOT NULL UNIQUE,
            pid            INTEGER NOT NULL REFERENCES mnids(pid) ON DELETE CASCADE,
            created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );

        CREATE INDEX IF NOT EXISTS idx_oauthtokens_pid ON oauthtokens(pid);


        CREATE TABLE IF NOT EXISTS independenttokens (
            token          TEXT PRIMARY KEY, 
            client_id       TEXT NOT NULL,
            pid            INTEGER NOT NULL REFERENCES mnids(pid) ON DELETE CASCADE,
            created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );

        CREATE INDEX IF NOT EXISTS idx_independenttokens_pid ON independenttokens(pid);


        CREATE TABLE IF NOT EXISTS nextokens (
            token          TEXT PRIMARY KEY, 
            game_id        TEXT NOT NULL,
            pid            INTEGER NOT NULL REFERENCES mnids(pid) ON DELETE CASCADE,
            created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );

        CREATE INDEX IF NOT EXISTS nextokens_pid ON nextokens(pid);

        CREATE TABLE IF NOT EXISTS nex_accounts (
            pid       INTEGER PRIMARY KEY REFERENCES mnids(pid) ON DELETE CASCADE,
            password  TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS servers (
            ip               TEXT,
            port             INTEGER,
            aes_key          TEXT NOT NULL,
            service_name     TEXT NOT NULL DEFAULT 'application',
            game_id          TEXT NOT NULL UNIQUE,
            access_level     INTEGER NOT NULL DEFAULT 0,
            client_id        TEXT NOT NULL UNIQUE,
            maintenance_mode BOOLEAN NOT NULL DEFAULT FALSE
        );

        CREATE TABLE IF NOT EXISTS devices (
            id                BIGSERIAL PRIMARY KEY,
            model             TEXT   NOT NULL,
            device_id         BIGINT NOT NULL,
            serial            TEXT,
            certificate_hash  TEXT   NOT NULL UNIQUE,
            soap_account_id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100000000 MINVALUE 100000000 MAXVALUE 999999999) UNIQUE
        );

        CREATE INDEX IF NOT EXISTS idx_devices_device_id ON devices(device_id);

        CREATE TABLE IF NOT EXISTS device_linked_pids (
            pid        INTEGER NOT NULL REFERENCES mnids(pid)  ON DELETE CASCADE,
            device_id  BIGINT  NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
            PRIMARY KEY (pid, device_id)
        );

        SELECT cron.schedule('cleanup-old-tokens', '*/5 * * * *', $$
            DELETE FROM oauthtokens        WHERE created_at < NOW() - INTERVAL '6 hours';
            DELETE FROM independenttokens  WHERE created_at < NOW() - INTERVAL '24 hours';
            DELETE FROM nextokens          WHERE created_at < NOW() - INTERVAL '2 hours';
        $$);
";

    // Creates all tables if they don't exist already
    public static async Task InitializeAsync(string connectionString)
    {
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();

        await using var tx = await connection.BeginTransactionAsync();
        await using var cmd = new NpgsqlCommand(Schema, connection, tx);
        await cmd.ExecuteNonQueryAsync();
        await tx.CommitAsync();
    }
}